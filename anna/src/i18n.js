export const dictionaries = { zh };

function detect() {
  try { const saved = localStorage.getItem(LANG_KEY); if (saved === 'zh' || saved === 'en') return saved; } catch {}
  return String(globalThis.navigator?.language || '').toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

let lang = detect();

export const getLang = () => lang;
export const locale = () => lang === 'zh' ? 'zh-CN' : undefined;

export function setLang(next) {
  lang = next === 'zh' ? 'zh' : 'en';
  try { localStorage.setItem(LANG_KEY, lang); } catch {}
}

export function t(key, vars) {
  const template = (lang === 'zh' && zh[key]) || key;
  return vars ? template.replace(/\{(\w+)\}/g, (match, name) => name in vars ? String(vars[name]) : match) : template;
}
